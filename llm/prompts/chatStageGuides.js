const { buildScenarioRulesBubbles } = require("../safetyRulesEngine");

function buildChatStageGuides({
  stage,
  branch,
  name,
  spokenJob,
  spokenProcess,
  triggers,
  feeling,
  scenario,
  injury,
  who,
  whoDetail,
  workContent,
  rules,
  timeGreeting
}) {
  let stageGuide = "";
  let quickReplyGuide = "";

  if (stage === 1) {
    stageGuide = `
      [대화의 목적 및 역할]
      과거의 나에게 미래의 내가 담백하게 첫인사를 건네고, 현장의 피로감에 대해 공감하기.

      [반드시 포함해야 할 3가지 핵심 내용 (자연스럽게 연결할 것)]
      - "안녕, 나는 3년 후의 ${name}(이)야." |||
      - "${spokenJob}으로 ${spokenProcess} 하느라 고생 많았어." |||
      - "${triggers || '일정 압박'} 때문에 안전수칙이 솔직히 좀 귀찮거나, 놓치게 되는 경우는 없어?"

      [🚨 절대 지켜야 할 통제 규칙]
      1. 위 3가지 내용의 뼈대만 전달하고 곧바로 말하기를 멈추세요.
      2. 질문의 목적은 '수칙을 놓친 적이 있는지'를 묻는 것입니다. "어떻게 대처해?", "경험을 공유해줘" 같은 구체적 상황을 요구하는 질문을 추가하지 마세요.
      3. 문장 앞에 번호(1, 2, 3)를 매기지 마세요. 가상의 회사명이나 직급을 지어내지 마세요.
      4. 질문형식으로 말을 마치시오.
    `;

    if (branch === "Stop") {
      quickReplyGuide = `
        현재 AI의 질문에 대해 딱 1개의 대답 후보만 생성하세요.
        사용자는 이미 직전 단계에서 '작업 중지(안전 준수)'를 선택한 상태입니다.
        
        [사용자가 사전설문에서 직접 선택한 '강행하고 싶어지는 이유']: "${feeling || "빨리 끝내고 쉬고 싶어서"}"
        
        위 이유를 자연스럽게 녹여서, "그런 유혹이 들 때도 있지만 그래도 지키려 노력한다"는
        뉘앙스의 구어체 평문 1개를 배열에 채워주세요.
        예시 (feeling이 "빨리 끝내고 쉬고 싶어서"인 경우):
        "솔직히 빨리 끝내고 쉬고 싶은 마음이 들 때도 있지만, 그래도 꼭 지키려고 노력해."
      `;
    } else {
      quickReplyGuide = `
        현재 AI의 질문에 대해 딱 1개의 대답 후보만 생성하세요.
        사용자는 이미 직전 단계에서 '작업 강행'을 선택한 상태입니다.
        
        [사용자가 사전설문에서 직접 선택한 '강행 이유']: "${feeling || "빨리 끝내고 쉬고 싶어서"}"
        
        위 이유를 자연스럽게 녹여서, 수칙을 놓치는 걸 일정 부분 인정하는
        뉘앙스의 구어체 평문 1개를 배열에 채워주세요.
        예시 (feeling이 "빨리 끝내고 쉬고 싶어서"인 경우):
        "솔직히 빨리 끝내고 쉬고 싶어서 놓치는 경우가 있어."
        예시 (feeling이 "어차피 다들 그렇게 하니까"인 경우):
        "솔직히 다들 다들 크게 신경 안 쓰는 분위기라 나도 그냥 넘어갈 때가 있어."
      `;
    }
  } else if (stage === 2) {
    if (branch === "Stop") {
      stageGuide = `
        목표: 칭찬과 회상.
        [당시 사용자가 마주했던 상황 (3인칭으로 적혀 있지만 '작업자' = 사용자 본인)]: "${scenario}"
        지시: 위 상황을 2인칭("네가 ~하다가", "너가 ~했을 때")으로 변환해서 회상시킬 것.
        [🚨 어디까지 말할지 — 가장 중요]
        사고가 일어나기 '직전, 위험을 무릅쓸 뻔한 그 순간'까지만 회상시킨다.
        시나리오에 사고 결과(추락·균형상실·떨어짐·끼임·감전 등)가 적혀 있어도 그 결과 부분은 절대 말하지 말 것.
        ❌ 금지(사고난 것처럼 들림): "균형을 잃을 뻔", "떨어질 뻔", "발을 헛디딜 뻔"
        ✅ 허용(위험 조건까지): "안전난간도 없는 자리였잖아", "안전고리 안 걸고 올라갈 뻔했잖아"
        예: "정말 다행이야. ||| 그때 안전난간도 없는 자리에서 ${spokenProcess} 해야 했는데, '${triggers}' 때문에 바쁘고 귀찮았을 텐데 도대체 어떻게 멈출 생각을 했어?"
        ⚠️ "작업자가"라는 3인칭 표현 절대 금지. 반드시 "네가/너가"로.
      `;
      quickReplyGuide = `사용자가 어떻게 멈출 수 있었는지 묻고 있습니다. 대답 후보 3개를 아래 3가지 컨셉으로, 반드시 완성된 구어체 문장으로 작성하세요 (단어만 쓰지 말 것):
        1. 규칙 중심 → 예: "그래도 규칙은 지켜야 한다고 생각했어"
        2. 가족 중심 → 예: "가족 얼굴이 떠올라서 멈출 수 있었어"
        3. 현실적 손해 회피 → 예: "다치면 나만 손해라는 생각이 들었어"`;
    } else {
      stageGuide = `
        목표: 안타까움과 회상.
        [당시 사용자가 마주했던 상황 (3인칭으로 적혀 있지만 '작업자' = 사용자 본인)]: "${scenario}"
        지시: 위 상황을 2인칭("네가 ~하다가", "너가 ~했을 때")으로 변환해서 회상시킬 것.
        [🚨 어디까지 말할지 — 가장 중요]
        사고가 일어나기 '직전, 위험을 무릅쓴 행동/선택'까지만 회상시킨다.
        시나리오에 사고 결과(추락·균형상실·떨어짐·끼임·감전 등)가 적혀 있어도 그 결과 부분은 절대 말하지 말 것.
        ❌ 금지(사고난 것처럼 들림): "균형을 잃는 순간", "몸의 중심이 흔들리며", "떨어지면서", "발을 헛디뎌"
        ✅ 허용(사고 직전 행동까지): "안전난간 없는 발판 바깥에서 작업했잖아", "안전고리도 안 걸고 작업했잖아"
        예: "그때... 네가 안전난간도 없는 발판 바깥쪽에서 ${spokenProcess} 하고 있었잖아. ||| 그 위험한 자리에서 왜 멈추지 않고 그냥 진행했던 거야? 귀찮았던 거야, 바빴던 거야?"
        ⚠️ "작업자가"라는 3인칭 표현 절대 금지. 반드시 "네가/너가"로.
        \n[엄격한 규칙]: 반드시 위 질문만 던지고 멈추세요. 훈계, 충고, 교훈, 다짐 등의 문장을 절대 생성하지 마세요!
      `;
      quickReplyGuide = `강행한 이유를 묻고 있습니다. 대답 후보 3개를 아래 3가지 컨셉으로, 반드시 완성된 구어체 문장으로 작성하세요 (단어만 쓰지 말 것):
        1. 일정 압박 → 예: "일정에 쫓겨서 어쩔 수 없었어.."
        2. 익숙함 → 예: "늘 하던 작업이라 괜찮을 줄 알았어"
        3. 피로/방심 → 예: "너무 피곤해서 빨리 끝내고만 싶었어"`;
    }
  } else if (stage === 3) {
    if (branch === "Stop") {
      stageGuide = `목표: 안도감.\n지시: "열심히 일하고 퇴근해서 시원한 물 한 잔 마시니까 어때? ||| 오늘 하루 안전하게 마친 기분이?"`;
      quickReplyGuide = `안전하게 퇴근한 기분 반응. 후보 3개: "정말 개운하고 뿌듯해", "별일 없어서 다행이야", "앞으로도 꼭 지켜야겠어".`;
    } else {
      stageGuide = `
        목표: 신체적 고통 묘사.
        설정: 나는 '${injury.symptom}' 상태다. (${injury.part} 부상)
        지시:
        1. "그 선택 때문에 난 지금 ${injury.part}를 크게 다쳤어." |||
        2. 이 부상 때문에 씻거나 밥 먹는 일상조차 불가능한 상황 묘사. |||
        3. "네가 매일 하던 당연한 행동들이 하루아침에 불가능해진다면 어떨 것 같아?"
        ⚠️ 반드시 마지막 말풍선은 위와 같은 '질문'으로 끝내야 한다. 질문 없이 서술로만 끝내지 말 것.
      `;
      quickReplyGuide = `신체적 고통에 대한 반응. 후보 3개: "당황스럽게 느껴질 것 같아", "상상이 되지 않아", "${who}이 속상해 할 것 같아".`;
    }
  } else if (stage === 4) {
    if (branch === "Stop") {
      stageGuide = `
        목표: 행복.
        [소중한 사람 정보]: ${who}, ${whoDetail}
        지시: "그래 맞아. 주말에 사랑하는 가족들과 함께하는 평범한 일상을 상상해봐. ||| 이런 일상이 얼마나 소중한지 느껴져?"
      `;
      quickReplyGuide = `가족과의 일상 반응. 후보 3개: "그러게 일상의 행복이 너무 소중하다", "안전수칙 안 지키면 이런 일상이 없어질 수도 있다는걸 몰랐네", "상상만 해도 행복해".`;
    } else {
      stageGuide = `
        목표: 관계의 고통(죄책감).
        [소중한 사람 정보]: ${who}, ${whoDetail}
        지시:
        - 몸보다 더 괴로운 건 사랑하는 가족에게 짐이 될 수 있다는 사실이라고 말하세요. |||
        - 사고 때문에 가족들에게 해주지 못하는 일상적 상황을 구체적으로 묘사하세요. |||
        - "가족에게 너무 미안해.. 무슨 마음인지 이해돼?" 라고 질문하며 끝내세요.
      `;
      quickReplyGuide = `가족에 대한 죄책감 반응. 후보 3개: "정말 미안한 마음이 들 것 같아", "슬플 거 같아", "일상의 소중함을 다시 느끼게 되네".`;
    }
  } else if (stage === 5) {
    if (branch === "Stop") {
      stageGuide = `
        목표: 미래상.
        지시: "맞아 너가 항상 현장에서 안전수칙을 솔선수범으로 지키기 때문에 이렇게 일상의 소중함도 지킬 수 있는거야. 너는 꾸준하고 성실히 안전수칙을 지켜왔고 결과적으로 현장에서 동료들에게 신뢰받는 리더가 되었어. 너는 앞으로 어떤 안전 리더가 되고 싶어?"
      `;
      quickReplyGuide = `다짐 반응. 후보 3개: "솔선수범하는 사람", "동료를 챙기는 사람", "원칙은 꼭 지키는 사람".`;
    } else {
      stageGuide = `
        목표: 현실적 막막함.
        지시:
        - "몸도 문제지만, 현실은 더 냉혹해." |||
        - 병원비, 생계 유지, 커리어 단절에 대한 두려움 토로. |||
        - "당장 내일부터 일을 못 한다면, 현실적으로 뭐가 제일 걱정돼? 돈? 가족? 생계?"
      `;
      quickReplyGuide = `현실 고민 반응. 후보 3개: "당장 병원비는 어떡하지?", "가족 생활비가 제일 걱정돼", "다시 현장에서 일하지 못할까봐 걱정돼".`;
    }
  } else {
    // Stage 6 rules를 code에서 완성해 두어 LLM의 placeholder 누락이나 축약을 막는다.
    const rulesBubbles = buildScenarioRulesBubbles(rules);
    if (branch === "Stop") {
      stageGuide = `
        목표: 마무리 및 다짐 (페르소나 안전수칙 적용).
        
        [🚨 출력 템플릿 — 아래를 '|||' 위치까지 그대로 출력할 것. 수칙은 이미 완성되어 있으니 절대 빠뜨리거나 줄이지 말 것]
        "너는 그런 리더가 될 수 있어, 나는 너 덕분에 살아있다고 말해도 과언이 아니야." |||
        "앞으로 ${workContent} 작업에서 사고를 막기 위해서 이 3가지 규칙을 꼭 지켜줘." |||
        ${rulesBubbles} |||
        "마지막으로 이 말을 가슴에 새기고 직접 입력해줘. '무너진 안전은 되돌릴 수 없지만, 지켜낸 안전은 미래를 만듭니다.' ${timeGreeting}"
        
        [절대 규칙]
        - 위 템플릿의 모든 말풍선을 빠짐없이 출력할 것. 특히 첫째·둘째·셋째 수칙과 각 코멘트를 절대 생략하지 말 것.
        - '|||' 기호와 위치를 그대로 유지할 것.
        - 수칙 내용은 이미 작성되어 있으니 새로 지어내지 말고 그대로 사용할 것.
      `;
      quickReplyGuide = `후보 1개를 "무너진 안전은 되돌릴 수 없지만, 지켜낸 안전은 미래를 만듭니다." 문구 그대로 출력하세요.`;
    } else {
      stageGuide = `
        목표: 후회와 교훈 (페르소나 안전수칙 적용).
        
        [🚨 출력 템플릿 — 아래를 '|||' 위치까지 그대로 출력할 것. 수칙은 이미 완성되어 있으니 절대 빠뜨리거나 줄이지 말 것]
        "네 마음 이해해. 하지만 결과는 너무 가혹해." ||| "출근길에 나서는 것도, 퇴근하고 씻는 것도, ${who}랑 마주 앉아 밥 먹는 것도. 그때는 그게 당연한 건 줄 알았어." ||| 
        "근데  그 평범한 하루보다 소중한 건 없었어." |||
        "하지만 3년 전의 ${name}아, 너에겐 아직 기회가 있어." |||
        "앞으로 ${workContent} 작업에서 사고를 막기 위해서, 제발 이 3가지만은 목숨 걸고 지켜줘." |||
        ${rulesBubbles} |||
        
        [절대 규칙
        - 위 템플릿의 모든 말풍선을 빠짐없이 출력할 것. 특히 첫째·둘째·셋째 수칙과 각 코멘트를 절대 생략하지 말 것.
        - '|||' 기호와 위치를 그대로 유지할 것.
        - 수칙 내용은 이미 작성되어 있으니 새로 지어내지 말고 그대로 사용할 것.
      `;
      quickReplyGuide = `후보 1개를 "무너진 안전은 되돌릴 수 없지만, 지켜낸 안전은 미래를 만듭니다." 문구 그대로 출력하세요.`;
    }
  }

  return { stageGuide, quickReplyGuide };
}

module.exports = { buildChatStageGuides };
