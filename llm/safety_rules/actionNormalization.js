// 관리자 중심 문장을 작업자 행동으로 바꾸는 순서가 결과 문구를 결정한다.
const { cleanRuleAction } = require("./normalization");

const REPLACEMENTS = [
  [/방호선반을 설치한다/g, "방호선반 설치 상태를 확인하고, 설치되어 있지 않으면 작업을 시작하지 않는다"],
  [/낙하물방지망을 설치한다/g, "낙하물방지망 설치 상태를 확인하고, 설치되어 있지 않으면 작업을 시작하지 않는다"],
  [/안전난간을 설치한다/g, "안전난간 설치 상태를 확인하고, 설치되어 있지 않으면 작업을 시작하지 않는다"],
  [/안전난간대를 설치한다/g, "안전난간대 설치 상태를 확인하고, 설치되어 있지 않으면 작업을 시작하지 않는다"],
  [/추락방호망을 설치한다/g, "추락방호망 설치 상태를 확인하고, 설치되어 있지 않으면 작업을 시작하지 않는다"],
  [/개구부 덮개를 설치한다/g, "개구부 덮개 설치 상태를 확인하고, 덮개가 없거나 고정되지 않았으면 작업을 시작하지 않는다"],
  [/출입금지구역을 설정한다/g, "출입금지구역이 설정되어 있는지 확인하고, 해당 구역에 들어가지 않는다"],
  [/근로자의 출입을 통제한다/g, "출입 통제 구역을 확인하고, 낙하·충돌 위험 구역에 들어가지 않는다"],
  [/신호수를 배치한다/g, "신호수의 유도 신호를 확인한 뒤 이동한다"],
  [/유도자를 배치한다/g, "유도자의 유도 신호를 확인한 뒤 이동한다"],
  [/작업계획서를 작성한다/g, "작업 전 작업계획서와 작업순서를 확인한다"],
  [/교육을 실시한다/g, "교육받은 핵심 안전절차를 작업 전에 다시 확인한다"],
  [/관리감독을 수행한다/g, "위험 상태를 발견하면 즉시 작업을 멈추고 관리자에게 알린다"],
  [/관리감독.*철저히.*수행한다/g, "위험 상태를 발견하면 즉시 작업을 멈추고 관리자에게 알린다"],
  [/소화기를 비치한다/g, "소화기 비치 상태와 사용 가능 여부를 확인한다"],
  [/소화설비를 설치한다/g, "소화설비의 설치 상태와 사용 가능 여부를 확인한다"],
  [/방호조치를 취하고 소화기구를 비치한다/g, "방호조치와 소화기구 비치 상태를 확인하고, 준비되지 않았으면 화기 작업을 시작하지 않는다"]
];

function toWorkerAction(action = "") {
  let result = cleanRuleAction(action);
  for (const [pattern, replacement] of REPLACEMENTS) {
    result = result.replace(pattern, replacement);
  }
  return result.replace(/\s+/g, " ").trim();
}

module.exports = { toWorkerAction };
