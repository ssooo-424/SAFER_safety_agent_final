function getTriggerCode(triggers = []) {
  const map = {
    "일정/생산 압박 (빨리빨리)": "T1",
    "반복 작업이라 익숙해서": "T2",
    "안전보호구/절차가 불편해서": "T3",
    "주변 동료들과의 의사소통 미흡": "T4",
    "작업 공간 협소/자재 정리 안됨": "T5",
    "위험이 눈에 잘 안 보여서": "T6",
    "피로/집중력 저하": "T7",
    "급박한 일정/압박": "T1",
    "반복·익숙함(늘 하던 일)": "T2",
    "안전보호구(PPE) 불편/귀찮음": "T3",
    "PPE 불편/귀찮음": "T3",
    "소통 부재/신호 혼선": "T4",
    "정리정돈 미흡/통로 장애": "T5",
    "시야 제한/사각지대": "T6",
    "야간·피로·집중저하": "T7"
  };
  for (const trigger of triggers || []) {
    if (map[trigger]) return map[trigger];
  }
  return "";
}

function classifyRuleCategory(text = "") {
  const s = String(text);
  if (/보안경|보안면|안전모|안전화|안전대|안전벨트|안전고리|생명줄|구명조끼|보호구|개인보호구|절연장갑|절연화|방열복|방진마스크|방독마스크|호흡용 보호구|송기마스크|장갑|토시|긴 옷|보호복|장화/.test(s)) return "PPE";
  if (/안전난간|안전난간대|개구부|덮개|작업발판|비계|말비계|물비계|고소작업대|추락방호망|추락 방호망|안전블럭|단부|추락방지|추락 방지|부착설비/.test(s)) return "FALL_PROTECTION";
  if (/낙하물방지망|방호선반|낙하|인양|양중|줄걸이|슬링|와이어로프|섬유로프|결속|자재.*전도|중량물|전용 적재대|적재|받침목|전도방지|전도 방지/.test(s)) return "FALLING_OBJECT";
  if (/출입금지|출입 금지|출입통제|출입 통제|접근금지|접근 금지|접근방지|위험구역|작업반경|회전반경|통제|펜스|방책|구획/.test(s)) return "ACCESS_CONTROL";
  if (/신호수|신호|유도자|유도 신호|복명복창|의사소통|연락 체계|무전|공유|협의|작업 지시/.test(s)) return "SIGNAL_COMMUNICATION";
  if (/정리정돈|정리|정돈|통로|장애물|적치|가연성 물질.*제거|인화성 물질.*제거|주변.*제거|작업장 주변/.test(s)) return "HOUSEKEEPING";
  if (/감전|전선|가설 전선|가공 배선|전동공구|누전|충전부|전원|차단|검전|절연|접근한계거리|활선|전기|피복|무전압|누전차단기/.test(s)) return "ELECTRICAL";
  if (/질식|산소|가스|유해가스|인화성가스|황화수소|농도|환기|통풍|급기|배기|배출구|밀폐공간|감시인|환기시설|국소배기|방독|송기/.test(s)) return "VENTILATION_GAS";
  if (/화재|화상|불티|용접|절단|산소절단|소화기|소화설비|방화포|불티방지|비산방지|점화원|인화물질|가연물|위험물|연료|난로|방화모래|잔여 불씨|폭발/.test(s)) return "FIRE_EXPLOSION";
  if (/끼임|회전부|톱날|둥근톱|방호덮개|안전 덮개|덮개|커버|방호장치|방호 조치|원동기|회전축|벨트|드럼|잠금|LOTO|운전 정지|정비|검사/.test(s)) return "MACHINE_GUARDING";
  if (/작업계획서|작업계획|작업 계획|작업순서|작업 절차|작업절차|표준 작업|절차|설치순서|구조검토서|도면|작업 준비/.test(s)) return "WORK_PLAN";
  if (/교육|관리감독|관리 감독|TBM|점검회의|MSDS|물질자료|안전인증|허가서|PTW|작업 허가/.test(s)) return "EDUCATION_MANAGEMENT";
  if (/장비|차량|지게차|굴삭기|굴착기|크레인|타워크레인|이동식 크레인|고소작업대|테이블 리프트|리프트|기중기|건설기계|기계적 상태|감속기/.test(s)) return "EQUIPMENT";
  return "GENERAL";
}

function accidentPriority(text = "", riskType = "") {
  const s = String(text);
  const risk = normalizeRiskType(riskType);
  const directMap = {
    추락: /안전난간|안전대|안전벨트|안전고리|생명줄|작업발판|개구부|덮개|추락방호망|비계|고소작업대|단부/,
    낙하: /낙하물방지망|방호선반|공구|자재|결속|출입금지|출입 통제|낙하 위험|인양|양중|슬링|로프/,
    끼임: /전원|차단|잠금|LOTO|방호장치|방호덮개|커버|회전부|벨트|드럼|협착|끼임|접근 금지|운전 정지/,
    충돌: /신호수|신호|유도자|작업반경|동선|분리|접근|장비|충돌|접촉/,
    붕괴: /지보공|거푸집|흙막이|버팀대|고정|지지|전도|붕괴|구조|깔림|받침목/,
    감전: /전원|차단|검전|절연|접근한계거리|활선|충전부|전선|전동공구|피복|누전|감전/,
    질식: /산소|가스|농도|환기|감시인|호흡용|밀폐|질식|황화수소|유해가스/,
    익사: /구명조끼|안전난간|빠짐|수상|물가/,
    절상: /보안경|보안면|톱날|둥근톱|회전부|절단|절상|베임|찔림|방호덮개|안전 덮개/,
    넘어짐: /미끄럼|미끄러운|정리|정돈|통로|작업발판|도막제|시트/
  };
  const secondaryMap = {
    추락: /출입금지|작업계획|작업순서|점검|교육|관리감독/,
    낙하: /정리|정돈|작업계획|점검|교육|관리감독/,
    끼임: /신호|작업계획|점검|교육|관리감독/,
    충돌: /작업계획|점검|교육|관리감독|정리|통로/,
    붕괴: /작업계획|점검|교육|관리감독|출입금지/,
    감전: /작업계획|점검|교육|관리감독|보호구/,
    질식: /작업계획|점검|교육|관리감독|보호구/,
    익사: /작업계획|점검|교육|관리감독/,
    절상: /작업계획|점검|교육|관리감독|보호구/,
    넘어짐: /작업계획|점검|교육|관리감독/
  };
  if (directMap[risk]?.test(s)) return 1;
  if (secondaryMap[risk]?.test(s)) return 2;
  return 3;
}

function triggerPriority(text = "", triggerCode = "") {
  const map = {
    T1: /작업 전|확인|점검|절차|작업계획|작업순서|준수|중지|생략/,
    T2: /다시 확인|재확인|체결|잠금|점검|체크|오늘|매번/,
    T3: /보호구|안전대|안전고리|안전모|보안경|착용|체결|절차/,
    T4: /신호|신호수|유도자|복명복창|공유|의사소통|보고|통제|협의/,
    T5: /정리|정돈|통로|자재|장애물|출입금지|위험구역|적치|구획/,
    T6: /사각지대|시야|조명|유도자|작업반경|접근|장비|확인/,
    T7: /피로|휴식|2인|집중|다시 확인|점검|컨디션/
  };
  return map[triggerCode]?.test(String(text)) ? 1 : 2;
}

